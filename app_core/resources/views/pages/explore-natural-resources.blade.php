<p>Kegalle sits at the edge of Sri Lanka's wet zone hill country, giving the district a mix of lowland forest, rivers and waterfalls that's easy to reach but rarely crowded.</p>

<h2>Samanala Reserve Forest</h2>
<p>A forest reserve area known for its biodiversity, popular with birdwatchers and nature walkers looking for a quieter alternative to the more well-known national parks further south.</p>

<h2>Kegalle Reservoir</h2>
<p>A calm, scenic spot used for irrigation and local fishing, the reservoir area is a good place for a relaxed evening walk or a picnic away from the main town.</p>

<h2>Rivers & Waterfalls</h2>
<p>The Kelani River runs through the district and feeds several of the district's waterfalls, including Bopath Ella. The river and its tributaries also support several smaller, lesser-known falls in the hills around Mawanella and Ruwanwella worth seeking out if you have local guidance.</p>

<h2>Visiting Responsibly</h2>
<p>Many of these natural areas are unmanaged or lightly managed — bring out what you bring in, and consider a local guide for anywhere off the main trails, especially during the rainy season when river levels can rise quickly.</p>

