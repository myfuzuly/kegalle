        <p>Kegalle district sits in Sri Lanka's wet zone, with fertile lowlands rising into the foothills of the central highlands. This geography makes the district one of the island's most productive agricultural regions, while its river systems and forest reserves support a rich natural environment.</p>

        <h2>Rubber</h2>
        <p>Kegalle is one of Sri Lanka's most important rubber-growing districts. Vast estates of Hevea brasiliensis (rubber trees) cover much of the lowland areas, and rubber tapping remains the livelihood of many families across the district. The latex is processed locally into sheets and exported through Colombo, and visiting a working rubber estate is a popular experience for visitors with an interest in agriculture.</p>

        <h2>Tea</h2>
        <p>As the land rises toward the central highlands, rubber estates give way to tea. While Kegalle's tea production is smaller in scale than Nuwara Eliya or Kandy, the higher-altitude areas around Mawanella and Aranayake produce good quality mid-grown teas. Tea factory visits can be arranged through local operators.</p>

        <h2>Gemstones</h2>
        <p>The Sabaragamuwa Province — which includes Kegalle district — is synonymous with Sri Lanka's gem trade. Sapphires, rubies, moonstones and cat's eyes are all found in the alluvial gravels of the region's rivers. Traditional gem pit mining remains active in parts of the district, and visitors can observe the process at several sites.</p>

        <h2>Rivers &amp; Water Resources</h2>
        <p>The Kelani River — one of Sri Lanka's major rivers — flows through the Kegalle district, providing water for agriculture, hydropower generation and daily life across the region. Several significant waterfalls, including Bopath Ella, form along tributaries of the Kelani. The rivers also support freshwater fish populations and are used for irrigation.</p>

        <h2>Forest Reserves</h2>
        <p>Parts of the district fall within designated forest reserves and the transition zone to the Knuckles and Peak Wilderness areas. These forests support a range of endemic wildlife including purple-faced langurs, giant squirrels and a variety of birdlife. Forest conservation and sustainable land use are active topics in the district's development planning.</p>

