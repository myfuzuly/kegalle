        <p>The Kegalle district sits within the Sabaragamuwa Province, a region that has been inhabited and significant in Sri Lankan history for over two millennia. Temples, ancient inscriptions and old trade routes all bear witness to the area's long past — and several well-preserved sites are accessible to visitors today.</p>

        <h2>Aranayake Rajamaha Viharaya</h2>
        <p>One of the most significant Buddhist temples in the district, Aranayake Rajamaha Viharaya is an ancient temple complex with rock cave shrines, inscriptions and traditional paintings. The site is an active place of worship and is considered of significant archaeological value. The surrounding hills and cave complexes have been associated with Buddhist monks since antiquity.</p>

        <h2>Dedigama — Ancient Capital</h2>
        <p>Dedigama, in the western part of the district, is believed to have been a significant settlement and possibly a royal capital during an earlier period of Sri Lankan history. Archaeological excavations in the area have uncovered remains of ancient structures, coins and artefacts. Dedigama is also associated with Parakramabahu I, one of Sri Lanka's most celebrated kings.</p>

        <h2>Mawanella &amp; Heritage Sites</h2>
        <p>The Mawanella area, in the central part of the district, contains several historic temples and dagobas (Buddhist stupas) of varying age and significance. The town itself grew along one of the old hill-country trading routes and retains some period architecture in its older commercial streets.</p>

        <h2>Colonial History</h2>
        <p>Like much of Sri Lanka's hill country, Kegalle district was shaped significantly by the British colonial period. The rubber industry was largely established by colonial planters, and the rail line through Rambukkana — opened in the 1860s — was built to connect the hill-country plantations to Colombo's port. Several estate bungalows and colonial-era buildings from this period survive in varying states of preservation across the district.</p>

        <h2>Planning a Heritage Visit</h2>
        <p>Most historic sites in the district are active temples or government-managed sites, and require respectful dress (shoulders and knees covered) when visiting. Early morning visits are generally quieter and better for photography. A local guide is invaluable for understanding the history and navigating less well-signed sites.</p>

