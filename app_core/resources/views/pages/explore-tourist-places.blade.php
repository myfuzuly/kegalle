<p>Kegalle is one of Sri Lanka's most underrated destinations — close enough to Colombo for an easy day trip, but with enough variety to fill a full weekend.</p>

<h2>Pinnawala Elephant Orphanage</h2>
<p>Sri Lanka's best-known elephant care centre, where rescued and orphaned elephants are raised and cared for. The riverside bathing sessions, where the herd walks down to the Maha Oya for a wash, are the highlight for most visitors and happen twice a day.</p>

<h2>Bopath Ella Falls</h2>
<p>One of Sri Lanka's widest and most photographed waterfalls, named for its leaf-like ("bo-path") shape. It's a short, easy walk from the parking area, making it accessible for most visitors, and the pool at the base is a popular spot to cool off.</p>

<h2>Bellena Cave</h2>
<p>An archaeological site with evidence of human settlement going back tens of thousands of years, Bellena (Belilena) Cave is one of the most significant prehistoric sites in Sri Lanka. It's a quieter, less touristy stop that's worth combining with a visit to the falls.</p>

<h2>Getting Around</h2>
<p>Most of these attractions are within a 30–45 minute drive of Kegalle town and can be combined into a single day's itinerary. Local tuk-tuk and taxi operators around the town and Mawanella are familiar with the routes.</p>

