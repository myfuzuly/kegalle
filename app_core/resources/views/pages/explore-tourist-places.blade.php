        <p>Kegalle district is one of Sri Lanka's most rewarding destinations for day trips from Colombo — within two hours by road you can be at a major wildlife sanctuary, a spectacular waterfall, or a centuries-old heritage site. Here are the most visited spots across the district.</p>

        <h2>Pinnawala Elephant Orphanage</h2>
        <p>Pinnawala is one of Sri Lanka's most iconic attractions, home to one of the world's largest herds of captive elephants. The orphanage rescues injured and orphaned elephants, and twice daily the herd walks down to the Maha Oya River for a bath — one of the most photographed moments in Sri Lanka. Visitors can watch from the riverbank or from the nearby viewing areas. Located about 13 km from Kegalle town.</p>

        <h2>Bopath Ella Falls</h2>
        <p>Bopath Ella (named for the shape of a Bo leaf formed by the water flow) is one of Sri Lanka's widest and most visited waterfalls. The walk in from the road is short and well-marked, and there's a natural pool at the base. It's at its most impressive during and just after the monsoon season, but worth a visit year-round.</p>

        <h2>Rambukkana</h2>
        <p>Rambukkana is the railhead for Kandy — trains to Kandy and beyond begin the famous hill country climb from here, and the station itself is a popular photo spot as trains use a rack-and-pinion system to manage the gradient. If you're arriving from Colombo by train, Rambukkana is your first stop in the Kegalle district.</p>

        <h2>Kegalle Town &amp; Surrounds</h2>
        <p>Kegalle town is the commercial centre of the district and a good base for exploring the surrounding areas. The weekly market, local temples and the Sabaragamuwa Provincial Council are all worth a look for those interested in local life. The district's scenic back roads — particularly through rubber-growing areas — are also popular with cyclists and self-drive travellers.</p>

        <h2>Getting There</h2>
        <p>Kegalle is about 80 km from Colombo via the A1 highway. Frequent bus services connect Colombo, Kandy and Kegalle, and the Colombo–Badulla main rail line passes through Rambukkana. A tuk-tuk or hire car is the easiest way to get between the district's attractions.</p>

