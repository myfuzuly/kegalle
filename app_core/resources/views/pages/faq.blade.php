<h2>Is it free to post an ad?</h2>
<p>Yes, posting a standard classified ad is completely free. Optional paid features like featured placement and store accounts have their own pricing, visible in your <a href="/dashboard/membership">membership</a> options.</p>
<h2>How do I contact a seller?</h2>
<p>Open any listing and use the Chat, Call, or WhatsApp buttons to reach the seller directly.</p>
<h2>How do I create a store?</h2>
<p>Register with the "Store / Business" account type, then create your store from your <a href="/dashboard/stores/create">dashboard</a>. Stores go live after a quick review.</p>
<h2>How long does a listing stay active?</h2>
<p>Listings stay active until you remove them or they expire based on your membership plan. You can manage all your ads from <a href="/dashboard/listings">My Listings</a>.</p>
<h2>What should I do if I suspect a scam?</h2>
<p>Use the "Report Ad" button on the listing, avoid sending any payment, and review our <a href="/safety-tips">Safety Tips</a>.</p>
<h2>How do I save a listing for later?</h2>
<p>Tap the heart icon on any listing card to save it. You can find all saved listings under <a href="/dashboard/favorites">My Favorites</a>.</p>
