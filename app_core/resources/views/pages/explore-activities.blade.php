        <p>Kegalle district sits in Sri Lanka's hill country transition zone, which makes it a great base for active travellers — there's everything from gentle riverside walks to full day treks, without the crowds you'll find further south.</p>

        <h2>Hiking &amp; Trekking</h2>
        <p>The hills around Kegalle, Mawanella and Aranayake offer a range of trekking routes through rubber and tea estates, forest reserve trails, and viewpoints looking out over the Kelani River valley. Most routes are doable in half a day with a local guide, and several connect to waterfalls along the way.</p>

        <h2>Water Activities</h2>
        <p>Bopath Ella Falls, one of Sri Lanka's widest and most photographed waterfalls, has a natural pool at its base that's popular for a swim after the short walk in. Further along the Kelani River, you'll find spots for a relaxed river dip or a guided riverside walk, especially in the Ruwanwella and Kitulgala-adjacent areas.</p>

        <h2>Camping &amp; Outdoor</h2>
        <p>Several eco-lodges and homestays in the hills around Kegalle offer basic camping setups or open-air stays, usually paired with a guided nature walk or a visit to a nearby waterfall. It's a good option if you want a slower-paced overnight trip rather than a day visit.</p>

        <h2>Planning Your Visit</h2>
        <p>Kegalle is roughly 2 hours from Colombo by road and well served by both bus and rail via Rambukkana station, making it an easy day trip or a relaxed overnight stay. Mornings tend to be clearer for hiking and photography — afternoons can bring short showers, especially during the monsoon months.</p>

